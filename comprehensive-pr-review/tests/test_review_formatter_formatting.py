"""Tests for comprehensive-pr-review/scripts/review_formatter.py formatting.

Covers the rendering rules exercised by the review comment: the verdict
heading, per-category section icons, and collapsible section structure. Run
with:

    python3 -m unittest discover comprehensive-pr-review/tests
"""
import importlib.util
import unittest
from pathlib import Path

_SCRIPT = Path(__file__).resolve().parents[1] / "scripts" / "review_formatter.py"
_spec = importlib.util.spec_from_file_location("review_formatter", _SCRIPT)
review_formatter = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(review_formatter)

ReviewFormatter = review_formatter.ReviewFormatter
DEFAULT_SECTION_ICON = review_formatter.DEFAULT_SECTION_ICON


def _section(title, **extra):
    return {"title": title, "body": f"- body for {title}", **extra}


class ReviewTitleTest(unittest.TestCase):
    def test_defaults_to_review_not_tool_name(self):
        """No review_title -> heading is 'Review Verdict:', not the tool name."""
        f = ReviewFormatter({
            "recommendation": "COMMENT",
            "review_metadata": {"tool_name": "comprehensive-pr-review"},
        })
        heading = f._format_summary().splitlines()[0]
        self.assertEqual(heading, "## Review Verdict: Automated Review Complete — Human Review Pending :eyes:")
        self.assertNotIn("Comprehensive", heading)

    def test_explicit_review_title_is_respected(self):
        f = ReviewFormatter({
            "recommendation": "APPROVE",
            "review_metadata": {"review_title": "Security"},
        })
        self.assertTrue(f._review_title() == "Security")
        self.assertIn("## Security Verdict:", f._format_summary())

    def test_footer_still_carries_tool_name(self):
        """The tool name is dropped from the heading but kept in the footer."""
        f = ReviewFormatter({
            "recommendation": "COMMENT",
            "review_metadata": {"tool_name": "comprehensive-pr-review", "tool_version": "0.5.1"},
        })
        self.assertIn("Generated by comprehensive-pr-review v0.5.1", f._format_footer())


class SectionIconTest(unittest.TestCase):
    def setUp(self):
        self.f = ReviewFormatter({})

    def test_each_category_gets_a_distinct_relevant_icon(self):
        expected = {
            "Change Analysis": ":mag:",
            "Code Review Results (3 Passes)": ":bug:",
            "Test Analysis": ":test_tube:",
            "Security Analysis": ":lock:",
            "Documentation Check": ":books:",
            "Test Execution Results": ":checkered_flag:",
            "Code Generation": ":sparkles:",
        }
        got = {t: self.f._auto_section_icon(t) for t in expected}
        self.assertEqual(got, expected)
        # All seven categories render as distinct icons (no generic :memo:).
        icons = list(expected.values())
        self.assertEqual(len(set(icons)), len(icons))
        self.assertNotIn(DEFAULT_SECTION_ICON, icons)

    def test_execution_matches_before_test(self):
        """'Test Execution' must win the flag icon, not the generic test tube."""
        self.assertEqual(self.f._auto_section_icon("Test Execution Results"), ":checkered_flag:")

    def test_unknown_title_falls_back_to_default(self):
        self.assertEqual(self.f._auto_section_icon("Miscellaneous Notes"), DEFAULT_SECTION_ICON)

    def test_empty_title_falls_back_to_default(self):
        self.assertEqual(self.f._auto_section_icon(""), DEFAULT_SECTION_ICON)
        self.assertEqual(self.f._auto_section_icon(None), DEFAULT_SECTION_ICON)

    def test_explicit_icon_key_overrides_title_derivation(self):
        rendered = self.f._format_section(_section("Change Analysis", icon="shield"))
        self.assertIn(":shield:", rendered)
        self.assertNotIn(":mag:", rendered)

    def test_section_rendered_as_collapsible_with_icon_in_heading(self):
        rendered = self.f._format_section(_section("Security Analysis"))
        self.assertIn("<details>", rendered)
        self.assertIn("<summary><h3>:lock: Security Analysis", rendered)


if __name__ == "__main__":
    unittest.main()
