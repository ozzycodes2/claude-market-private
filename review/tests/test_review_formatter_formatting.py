"""Tests for review/scripts/review_formatter.py formatting.

Covers the rendering rules exercised by the review comment: the verdict
heading, per-category section icons, and collapsible section structure. Run
with:

    python3 -m unittest discover review/tests
"""
import contextlib
import importlib.util
import io
import unittest
from pathlib import Path

_SCRIPT = Path(__file__).resolve().parents[1] / "scripts" / "review_formatter.py"
_spec = importlib.util.spec_from_file_location("review_formatter", _SCRIPT)
review_formatter = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(review_formatter)

ReviewFormatter = review_formatter.ReviewFormatter
DEFAULT_SECTION_ICON = review_formatter.DEFAULT_SECTION_ICON
conventional_prefix = review_formatter.conventional_prefix
emojify_summary = review_formatter.emojify_summary
suggestion_fence = review_formatter.suggestion_fence
has_suggested_change = review_formatter.has_suggested_change


def _section(title, **extra):
    return {"title": title, "body": f"- body for {title}", **extra}


class ReviewTitleTest(unittest.TestCase):
    def test_defaults_to_review_not_tool_name(self):
        """No review_title -> heading is 'Review Verdict:', not the tool name."""
        f = ReviewFormatter({
            "recommendation": "COMMENT",
            "review_metadata": {"tool_name": "comprehensive-pr-review"},
        })
        heading = f._format_summary().splitlines()[0]
        self.assertEqual(heading, "## Review Verdict: Automated Review Complete — Human Review Pending :eyes:")
        self.assertNotIn("Comprehensive", heading)

    def test_explicit_review_title_is_respected(self):
        f = ReviewFormatter({
            "recommendation": "APPROVE",
            "review_metadata": {"review_title": "Security"},
        })
        self.assertTrue(f._review_title() == "Security")
        self.assertIn("## Security Verdict:", f._format_summary())

    def test_footer_still_carries_tool_name(self):
        """The tool name is dropped from the heading but kept in the footer."""
        f = ReviewFormatter({
            "recommendation": "COMMENT",
            "review_metadata": {"tool_name": "comprehensive-pr-review", "tool_version": "0.5.1"},
        })
        self.assertIn("Generated by comprehensive-pr-review v0.5.1", f._format_footer())


class FooterTest(unittest.TestCase):
    """Attribution is carried, but nothing in the footer renders."""

    def _footer(self, **metadata):
        return ReviewFormatter({"review_metadata": metadata})._format_footer()

    def test_attribution_is_an_html_comment_not_visible_text(self):
        footer = self._footer(tool_name="review", tool_version="0.10.1")
        self.assertIn("<!-- Generated by review v0.10.1 -->", footer)
        self.assertNotIn("<sub>", footer)

    def test_double_dash_does_not_terminate_the_comment_early(self):
        footer = self._footer(tool_name="review", model="us.anthropic.claude--opus-5")
        self.assertEqual(footer.count("--"), 2)  # the comment's own delimiters

    def test_declared_stages_render_nothing(self):
        f = ReviewFormatter({
            "recommendation": "COMMENT",
            "rationale": "ok",
            "sections": [_section("Change Analysis")],
            "review_metadata": {
                "tool_name": "review",
                "stages": ["Change Analysis", "QR Passes", "Security"],
            },
        })
        body = f.format_body()
        self.assertNotIn("Review Stages Executed", body)
        self.assertNotIn("MISSING", body)


class EmojifySummaryTest(unittest.TestCase):
    def test_counted_severities_keep_the_count(self):
        self.assertEqual(
            emojify_summary("1 critical, 2 high, 3 medium, 4 low"),
            "1 :rotating_light:, 2 :red_circle:, 3 :yellow_circle:, 4 :large_blue_circle:",
        )

    def test_plural_and_mixed_case_severities(self):
        self.assertEqual(emojify_summary("2 Criticals"), "2 :rotating_light:")

    def test_decorations_swap_with_or_without_a_count(self):
        self.assertEqual(emojify_summary("2 blocking"), "2 :no_entry:")
        self.assertEqual(emojify_summary("non-blocking"), ":speech_balloon:")
        self.assertEqual(emojify_summary("if-minor"), ":small_blue_diamond:")

    def test_non_blocking_wins_over_blocking(self):
        self.assertNotIn(":no_entry:", emojify_summary("all non-blocking"))

    def test_uncounted_severity_words_in_prose_survive(self):
        self.assertEqual(
            emojify_summary("high cardinality label, low risk"),
            "high cardinality label, low risk",
        )

    def test_empty_input_passes_through(self):
        self.assertEqual(emojify_summary(""), "")

    def test_applied_to_the_collapsed_section_summary(self):
        rendered = ReviewFormatter({})._format_section(
            _section("Security Analysis", summary_line="3 medium, 2 blocking")
        )
        self.assertIn("3 :yellow_circle:, 2 :no_entry:", rendered)
        self.assertNotIn("medium", rendered)


class SectionIconTest(unittest.TestCase):
    def setUp(self):
        self.f = ReviewFormatter({})

    def test_each_category_gets_a_distinct_relevant_icon(self):
        expected = {
            "Change Analysis": ":mag:",
            "Code Review Results (2 Passes)": ":bug:",
            "Test Analysis": ":test_tube:",
            "Domain & Architecture": ":triangular_ruler:",
            "Data & Contracts": ":handshake:",
            "Ops & Reliability": ":gear:",
            "Change & Evolution": ":seedling:",
            "Security Analysis": ":lock:",
            "Documentation Check": ":books:",
            "Test Execution Results": ":checkered_flag:",
            "Code Generation": ":sparkles:",
        }
        got = {t: self.f._auto_section_icon(t) for t in expected}
        self.assertEqual(got, expected)
        # Every category renders as a distinct icon (no generic :memo:).
        icons = list(expected.values())
        self.assertEqual(len(set(icons)), len(icons))
        self.assertNotIn(DEFAULT_SECTION_ICON, icons)

    def test_execution_matches_before_test(self):
        """'Test Execution' must win the flag icon, not the generic test tube."""
        self.assertEqual(self.f._auto_section_icon("Test Execution Results"), ":checkered_flag:")

    def test_evolution_matches_before_change(self):
        """'Change & Evolution' must not collide with 'Change Analysis'."""
        self.assertEqual(self.f._auto_section_icon("Change & Evolution"), ":seedling:")
        self.assertEqual(self.f._auto_section_icon("Change Analysis"), ":mag:")

    def test_unknown_title_falls_back_to_default(self):
        self.assertEqual(self.f._auto_section_icon("Miscellaneous Notes"), DEFAULT_SECTION_ICON)

    def test_empty_title_falls_back_to_default(self):
        self.assertEqual(self.f._auto_section_icon(""), DEFAULT_SECTION_ICON)
        self.assertEqual(self.f._auto_section_icon(None), DEFAULT_SECTION_ICON)

    def test_explicit_icon_key_overrides_title_derivation(self):
        rendered = self.f._format_section(_section("Change Analysis", icon="shield"))
        self.assertIn(":shield:", rendered)
        self.assertNotIn(":mag:", rendered)

    def test_section_rendered_as_collapsible_with_icon_in_heading(self):
        rendered = self.f._format_section(_section("Security Analysis"))
        self.assertIn("<details>", rendered)
        self.assertIn("<summary><h3>:lock: Security Analysis", rendered)


class ConventionalPrefixTest(unittest.TestCase):
    """The prefix always resolves to a valid conventionalcomments.org label."""

    def test_severity_defaults(self):
        cases = {
            "critical": "issue (blocking)",
            "high": "issue (blocking)",
            "medium": "suggestion (non-blocking)",
            "low": "nitpick (non-blocking)",
        }
        for sev, expected in cases.items():
            self.assertEqual(conventional_prefix({"severity": sev}), expected)

    def test_unknown_or_missing_severity_falls_back_to_thought(self):
        self.assertEqual(conventional_prefix({}), "thought")
        self.assertEqual(conventional_prefix({"severity": "bogus"}), "thought")

    def test_explicit_label_and_decoration_override_severity(self):
        got = conventional_prefix(
            {"severity": "critical", "label": "question", "decoration": "if-minor"}
        )
        self.assertEqual(got, "question (if-minor)")

    def test_explicit_label_keeps_severity_decoration(self):
        """A valid label without its own decoration keeps the severity default."""
        got = conventional_prefix({"severity": "critical", "label": "question"})
        self.assertEqual(got, "question (blocking)")

    def test_supported_labels(self):
        for label in ("praise", "nitpick", "suggestion", "issue", "thought", "question"):
            self.assertEqual(conventional_prefix({"label": label}), label)

    def test_unsupported_label_falls_back_to_severity_default(self):
        """Labels outside the supported set (e.g. todo/chore/note) fall back."""
        for label in ("todo", "chore", "note"):
            self.assertEqual(
                conventional_prefix({"severity": "critical", "label": label}),
                "issue (blocking)",
            )

    def test_invalid_label_and_decoration_fall_back(self):
        got = conventional_prefix(
            {"severity": "medium", "label": "wat", "decoration": "nope"}
        )
        self.assertEqual(got, "suggestion (non-blocking)")

    def test_label_matching_is_case_insensitive(self):
        got = conventional_prefix({"label": "SUGGESTION", "decoration": "Non-Blocking"})
        self.assertEqual(got, "suggestion (non-blocking)")


